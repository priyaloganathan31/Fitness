/**
 * Generates and triggers download of an iCalendar (.ics) file
 */
export function downloadIcsFile(event: CalendarEventOptions): void {
  const { startStr, endStr } = formatCalendarDates(event.dueDate);
  const uid = `fc-audit-${Date.now()}-${Math.random().toString(36).substring(2, 7)}@bitsathy.ac.in`;
  const cleanDescription = (event.description || '').replace(/\n/g, '\\n');
  
  const icsContent = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Campus FC Smart Audit System//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    'BEGIN:VEVENT',
    `UID:${uid}`,
    `DTSTAMP:${startStr}`,
    `DTSTART:${startStr}`,
    `DTEND:${endStr}`,
    `SUMMARY:[FC Audit] ${event.title}`,
    `DESCRIPTION:${cleanDescription} | Priority: ${event.priority || 'NORMAL'}`,
    `LOCATION:${event.location}`,
    'STATUS:CONFIRMED',
    `PRIORITY:${event.priority === 'HIGH' || event.priority === 'URGENT' ? 1 : 5}`,
    'BEGIN:VALARM',
    'TRIGGER:-PT24H',
    'ACTION:DISPLAY',
    'DESCRIPTION:Reminder: Campus FC Audit Due Tomorrow',
    'END:VALARM',
    'END:VEVENT',
    'END:VCALENDAR'
  ].join('\r\n');
  
  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', `FC-Audit-${event.title.replace(/[^a-zA-Z0-9]/g, '_')}-${event.dueDate}.ics`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
