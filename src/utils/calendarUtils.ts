export interface CalendarEventOptions {
  title: string;
  description: string;
  location: string;
  dueDate: string; // YYYY-MM-DD
  priority?: string;
  auditorName?: string;
}

/**
 * Dynamically computes a smart default due date based on venue schedule or priority SLA.
 */
export function calculateDynamicDueDate(
  venue?: { nextAuditDueDate?: string; scheduleFrequencyDays?: number },
  priority?: string
): string {
  const today = new Date();
  
  // 1. If venue has an explicit scheduled due date from registry, use it
  if (venue?.nextAuditDueDate && venue.nextAuditDueDate.trim() !== '') {
    return venue.nextAuditDueDate;
  }
  
  // 2. Otherwise calculate based on priority SLA offset
  let daysToAdd = 7; // Default medium priority standard
  if (priority === 'HIGH' || priority === 'URGENT') {
    daysToAdd = 3;
  } else if (priority === 'LOW' || priority === 'ROUTINE') {
    daysToAdd = 14;
  } else if (venue?.scheduleFrequencyDays && venue.scheduleFrequencyDays > 0) {
    daysToAdd = venue.scheduleFrequencyDays;
  }
  
  const targetDate = new Date(today.getTime() + daysToAdd * 86400000);
  return targetDate.toISOString().split('T')[0];
}

/**
 * Format a YYYY-MM-DD date into YYYYMMDDTHHmmssZ for calendar URLs (UTC time: 09:00:00 to 17:00:00 local standard)
 */
function formatCalendarDates(dueDateStr: string): { startStr: string; endStr: string; isoStart: string; isoEnd: string } {
  try {
    const parts = dueDateStr.split('-');
    if (parts.length === 3) {
      const year = parseInt(parts[0], 10);
      const month = parseInt(parts[1], 10) - 1;
      const day = parseInt(parts[2], 10);
      
      const start = new Date(Date.UTC(year, month, day, 9, 0, 0));
      const end = new Date(Date.UTC(year, month, day, 17, 0, 0));
      
      const formatUtc = (d: Date) => d.toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
      
      return {
        startStr: formatUtc(start),
        endStr: formatUtc(end),
        isoStart: start.toISOString(),
        isoEnd: end.toISOString()
      };
    }
  } catch (e) {
    console.error('Date parsing error:', e);
  }
  
  // Fallback
  const now = new Date();
  const cleanNow = now.toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
  return {
    startStr: cleanNow,
    endStr: cleanNow,
    isoStart: now.toISOString(),
    isoEnd: now.toISOString()
  };
}

/**
 * Generates a pre-filled Google Calendar web URL
 */
export function getGoogleCalendarUrl(event: CalendarEventOptions): string {
  const { startStr, endStr } = formatCalendarDates(event.dueDate);
  const title = encodeURIComponent(`[FC Audit] ${event.title}`);
  const details = encodeURIComponent(
    `Campus Fitness Certificate (FC) Audit Task\n\n` +
    `📍 Location: ${event.location}\n` +
    `⚡ Priority: ${event.priority || 'NORMAL'}\n` +
    `👤 Auditor: ${event.auditorName || 'Assigned Certified Auditor'}\n` +
    `📝 Notes: ${event.description}\n\n` +
    `Generated by Campus FC Smart Audit System`
  );
  const location = encodeURIComponent(event.location);
  
  return `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${title}&dates=${startStr}/${endStr}&details=${details}&location=${location}`;
}

